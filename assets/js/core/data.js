/* Data access layer: merges vocabulary with authored lesson content. */
(function () {
  const HY = window.HY;
  const V = window.HY_VOCAB || { lessons: [], words: [], gap: [], hsk4: [] };
  const C = window.HY_LESSONS || [];

  const words = {};       // book words by hanzi
  const gap = {};         // exam-gap words by hanzi
  const hsk4 = {};        // HSK4 words by hanzi
  const dict = {};        // lookup: all of the above, book preferred

  V.words.forEach((w) => { words[w.w] = w; dict[w.w] = w; });
  V.gap.forEach((w) => { gap[w.w] = w; if (!dict[w.w]) dict[w.w] = w; });
  V.hsk4.forEach((w) => { hsk4[w.w] = w; if (!dict[w.w]) dict[w.w] = w; });

  const contentByN = {};
  C.forEach((c) => { contentByN[c.n] = c; });

  const lessons = V.lessons.map((L) => {
    const c = contentByN[L.n] || null;
    return {
      n: L.n,
      zh: L.zh,
      en: L.en,
      book: L.book,
      items: L.items,
      content: c,
    };
  });
  const lessonByN = {};
  lessons.forEach((l) => { lessonByN[l.n] = l; });

  const studyWords = []; // book order then gap order
  V.words.forEach((w) => studyWords.push({ ...w, source: "book" }));
  V.gap.forEach((w) => studyWords.push({ ...w, source: "gap", lesson: 0 }));

  const wordIndex = {};
  studyWords.forEach((w, i) => { wordIndex[w.w] = w; w.idx = i; });

  // Reference dictionary for the reading passages: every word and character they
  // use, with pinyin, a gloss and a frequency. Generated by tools/build_tapdata.py
  // and precached by the service worker. Without tap.js (an older checkout) the
  // passage still renders and every character still opens the dialog.
  const TAP = window.HY_TAP || { words: {}, chars: {} };
  const tapWords = TAP.words || {};
  const tapChars = TAP.chars || {};
  const tapFreq = {};
  for (const w of Object.keys(tapWords)) tapFreq[w] = tapWords[w][2] || 1;
  for (const c of Object.keys(tapChars)) tapFreq[c] = Math.max(tapChars[c][2] || 1, tapFreq[c] || 0);
  let tapTotal = 0;
  for (const key in tapFreq) tapTotal += tapFreq[key];
  const TAP_LOG_TOTAL = Math.log(tapTotal || 1);
  const TAP_MAX_WORD = 6;
  const CJK_ONLY = /^[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]+$/;

  function tapEntry(text) {
    const word = tapWords[text];
    if (word) return { w: text, py: word[0], en: word[1], freq: word[2] || 0, reference: true };
    const char = tapChars[text];
    if (char) return { w: text, py: char[0], en: char[1], freq: char[2] || 0, alts: char[3] || "", reference: true };
    return null;
  }

  /** Any tap target: a course word first, then the reading reference dictionary. */
  function define(text) {
    const key = String(text == null ? "" : text);
    const core = dict[key];
    if (core && core.py && core.en) return core;
    // A few deck entries are missing a gloss; prefer the complete reference entry.
    return tapEntry(key) || core || null;
  }

  // Viterbi segmentation over the tap dictionary. Word frequencies decide the
  // boundaries, so 周末 stays one word and 的 is read as a particle. Every
  // Chinese character is a fallback token, which keeps the whole passage tappable.
  function tokenize(text) {
    const chars = Array.from(text || "");
    const n = chars.length;
    if (!n) return [];
    const score = new Float64Array(n + 1);
    const back = new Int32Array(n + 1);
    for (let i = 1; i <= n; i++) {
      let best = score[i - 1] + Math.log(tapFreq[chars[i - 1]] || 1) - TAP_LOG_TOTAL;
      let cut = i - 1;
      const maxLen = Math.min(TAP_MAX_WORD, i);
      for (let len = 2; len <= maxLen; len++) {
        const cand = chars.slice(i - len, i).join("");
        const f = tapFreq[cand];
        if (!f) continue;
        const value = score[i - len] + Math.log(f) - TAP_LOG_TOTAL;
        if (value > best) { best = value; cut = i - len; }
      }
      score[i] = best;
      back[i] = cut;
    }
    const out = [];
    let i = n;
    while (i > 0) {
      const cut = back[i];
      const tok = chars.slice(cut, i).join("");
      out.push({ t: tok, w: CJK_ONLY.test(tok) ? tok : null });
      i = cut;
    }
    return out.reverse();
  }

  let examples = null;
  function buildExamples() {
    examples = {};
    for (const L of lessons) {
      if (!L.content) continue;
      const c = L.content;
      const bucket = [];
      bucket.push({ zh: c.reading.text, en: c.reading.translation, src: "Reading · Lesson " + L.n });
      c.listening.dictation.forEach((s) => bucket.push({ zh: s, src: "Dictation · Lesson " + L.n }));
      (c.grammar.examples || []).forEach((e) => bucket.push({ zh: e.zh, en: e.en, src: "Grammar · Lesson " + L.n }));
      const own = new Set(L.items);
      const sents = [];
      for (const b of bucket) {
        for (const s of HY.util.splitSentences(b.zh)) sents.push({ zh: s, en: b.en, src: b.src });
      }
      for (const w of own) {
        if (w.length < 2) continue;
        const hits = sents.filter((s) => s.zh.includes(w)).slice(0, 2);
        if (hits.length) examples[w] = hits;
      }
    }
  }

  HY.data = {
    vocab: V,
    lessons,
    lessonByN,
    words,
    gap,
    hsk4,
    dict,
    studyWords,
    wordIndex,
    tokenize,
    define,
    tap: { words: tapWords, chars: tapChars },
    lookup: (w) => dict[w] || null,
    word: (w) => wordIndex[w] || dict[w] || null,
    lessonItems: (n) => (lessonByN[n] ? lessonByN[n].items : []),
    content: (n) => (lessonByN[n] ? lessonByN[n].content : null),
    examplesFor(w) {
      if (!examples) buildExamples();
      return examples[w] || [];
    },
    posOf(w) {
      const d = dict[w];
      return d ? d.pos : "";
    },
    level(w) {
      if (words[w]) return "book";
      if (gap[w]) return "gap";
      if (hsk4[w]) return "hsk4";
      return "";
    },
    meta: V.meta
  };

  HY.data.allTags = { book: "Book", gap: "Exam list", hsk4: "HSK4" };
})();

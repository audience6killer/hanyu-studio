import json, sys, os, re
sys.stdout.reconfigure(encoding="utf-8")
m=json.load(open("data-src/merged.json",encoding="utf-8"))
words={w["w"]:w for w in m["words"]}
by=[]
for L in m["lessons"]:
    items=[]
    for w in L["items"]:
        d=words[w]
        items.append({"w":w,"py":d["py"],"pos":d["pos"],"en":d["en"],"official":d["official"],"in_hsk6":d["in_hsk6"]})
    by.append({"lesson":L["n"],"zh":L["zh"],"en":L["en"],"book":L["book"],"items":items})
json.dump(by,open("content/vocab-by-lesson.json","w",encoding="utf-8"),ensure_ascii=False,indent=1)

# App data (JS global, file:// friendly)
app={
 "meta":m["meta"],
 "lessons":[{"n":L["n"],"zh":L["zh"],"en":L["en"],"book":L["book"],"items":L["items"]} for L in m["lessons"]],
 "words":[{"w":w["w"],"py":w["py"],"pos":w["pos"],"en":w["en"],"defs":w["defs"][:3],
           "lesson":w["lesson"],"also":w["also"],"official":w["official"],"in4":w["in_hsk4"],"in6":w["in_hsk6"],
           "trad":w["trad"],"rad":w["rad"],"freq":w["freq"]} for w in m["words"]],
 "gap":[{"w":g["w"],"py":g["py"],"pos":g["pos"],"en":g["en"],"defs":g["defs"][:3],"freq":g["freq"],"trad":g["trad"],"rad":g["rad"],"id":g["id"]} for g in m["gap"]],
 "hsk4":[{"w":g["w"],"py":g["py"],"pos":g["pos"][0] if g["pos"] else "","en":g["en"],"defs":g["defs"][:2],"freq":g["freq"]} for g in m["hsk4"]],
}
os.makedirs("assets/js/data",exist_ok=True)
with open("assets/js/data/vocab.js","w",encoding="utf-8") as f:
    f.write("/* Generated by tools/export_source.py - HSK vocabulary data (CC-CEDICT glosses, HSK 2.0 lists). */\n")
    f.write("window.HY_VOCAB = "+json.dumps(app,ensure_ascii=False,separators=(",",":"))+";\n")
print("vocab.js bytes",os.path.getsize("assets/js/data/vocab.js"))
print("lessons",len(by),"book words",len(m["words"]),"gap",len(m["gap"]),"hsk4",len(m["hsk4"]))

import json, os, sys
sys.stdout.reconfigure(encoding="utf-8")
vocab=json.load(open("content/vocab-by-lesson.json",encoding="utf-8"))
out=[]
for L in vocab:
    n=L["lesson"]
    c=json.load(open(f"content/lesson-{n:02d}.json",encoding="utf-8"))
    assert c["lesson"]==n
    assert c["title_zh"]==L["zh"], (n,c["title_zh"],L["zh"])
    out.append({
      "n":n,"zh":L["zh"],"en":L["en"],"book":L["book"],
      "theme":c["theme"],
      "grammar":c["grammar"],
      "reading":c["reading"],
      "listening":c["listening"],
      "writing":c["writing"]
    })
js="window.HY_LESSONS = "+json.dumps(out,ensure_ascii=False,separators=(",",":"))+";\n"
open("assets/js/data/lessons.js","w",encoding="utf-8").write("/* Generated by tools/build_content.py - original study content, one unit per textbook lesson. */\n"+js)
chars=sum(len(x["reading"]["text"]) for x in out)
print("lessons",len(out),"bytes",os.path.getsize("assets/js/data/lessons.js"),"reading chars",chars)
print("grammar points",len({x["grammar"]["point"] for x in out}))
print("dictation sentences",sum(len(x["listening"]["dictation"]) for x in out))
print("drills",sum(len(x["grammar"]["drills"]) for x in out),"questions",sum(len(x["reading"]["questions"]) for x in out))
